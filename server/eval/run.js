/**
 * Evaluation harness — measures the pipeline against hand-labelled ground truth
 * and prints/writes an honest benchmark table (plan.md §8).
 *
 * It scores the data ALREADY produced by the real seed run (no new Gemma calls):
 * each report's stored gemmaOutput vs eval/gold.js, the actual issue merges vs
 * the gold clusters, and real latency from the gemma_calls audit log.
 *
 *   npm run eval           # reads the live/seeded DB via MONGODB_URI
 *
 * Publishes both the good and the bad numbers — a project judges trust more when
 * it names its own weaknesses, and nobody else in a 48h sprint brings measured
 * results.
 */
import 'dotenv/config';
import fs from 'node:fs';
import mongoose from 'mongoose';

import { connectDb } from '../src/lib/db.js';
import { Report } from '../src/models/Report.js';
import { GemmaCall } from '../src/models/GemmaCall.js';
import { GOLD } from './gold.js';

const pctl = (arr, p) => {
  if (!arr.length) return null;
  const s = [...arr].sort((a, b) => a - b);
  return s[Math.min(s.length - 1, Math.floor((p / 100) * s.length))];
};
const pct = (n, d) => (d ? `${((100 * n) / d).toFixed(1)}%` : 'n/a');
const s1 = (ms) => (ms == null ? 'n/a' : `${(ms / 1000).toFixed(1)}s`);

async function main() {
  const uri = process.env.MONGODB_URI;
  if (!uri) {
    console.error('MONGODB_URI is not set (need the seeded DB). See DEPLOY.md.');
    process.exit(1);
  }
  await connectDb(uri);

  const reports = await Report.find().lean();
  const goldByText = new Map(GOLD.map((g) => [g.text.trim(), g]));

  let matched = 0;
  let scored = 0;
  let manualReview = 0;
  let catCorrect = 0;
  let sevExact = 0;
  let sevWithin1 = 0;
  const gCluster = [];
  const pCluster = [];

  for (const r of reports) {
    const g = goldByText.get((r.rawText || '').trim());
    if (!g) continue;
    matched += 1;

    const out = r.gemmaOutput;
    if (!out || out._manualReview || r.status === 'manual_review' || r.status === 'failed') {
      manualReview += 1;
      continue;
    }
    scored += 1;
    if (out.category === g.category) catCorrect += 1;
    const diff = Math.abs(Number(out.severity) - g.severity);
    if (diff === 0) sevExact += 1;
    if (diff <= 1) sevWithin1 += 1;

    gCluster.push(g.clusterId);
    pCluster.push(String(r.issueId));
  }

  // Pairwise dedupe precision/recall over the scored reports.
  let tp = 0;
  let fp = 0;
  let fn = 0;
  for (let i = 0; i < gCluster.length; i += 1) {
    for (let j = i + 1; j < gCluster.length; j += 1) {
      const sameGold = gCluster[i] === gCluster[j];
      const samePred = pCluster[i] === pCluster[j] && pCluster[i] !== 'null';
      if (sameGold && samePred) tp += 1;
      else if (!sameGold && samePred) fp += 1;
      else if (sameGold && !samePred) fn += 1;
    }
  }
  const precision = tp + fp ? tp / (tp + fp) : null;
  const recall = tp + fn ? tp / (tp + fn) : null;
  const f1 = precision != null && recall != null && precision + recall ? (2 * precision * recall) / (precision + recall) : null;

  // Latency + JSON reliability from the audit log.
  const calls = await GemmaCall.find().lean();
  const lat = (stage) => calls.filter((c) => (!stage || c.stage === stage) && Number.isFinite(c.latencyMs)).map((c) => c.latencyMs);
  const triageLat = lat('triage');
  const allLat = lat(null);
  const parseFail = calls.filter((c) => c.parsedOk === false).length;

  const rows = [
    ['Reports scored', `${scored} / ${matched}${manualReview ? ` (${manualReview} → manual review)` : ''}`],
    ['Category accuracy', `${pct(catCorrect, scored)} (${catCorrect}/${scored})`],
    ['Severity — exact match', `${pct(sevExact, scored)} (${sevExact}/${scored})`],
    ['Severity — within ±1', `${pct(sevWithin1, scored)} (${sevWithin1}/${scored})`],
    ['Dedupe precision', precision == null ? 'n/a' : precision.toFixed(3)],
    ['Dedupe recall', recall == null ? 'n/a' : recall.toFixed(3)],
    ['Dedupe F1', f1 == null ? 'n/a' : f1.toFixed(3)],
    ['JSON parse success', `${pct(calls.length - parseFail, calls.length)} (${calls.length - parseFail}/${calls.length} calls)`],
    ['Latency — triage p50 / p95', `${s1(pctl(triageLat, 50))} / ${s1(pctl(triageLat, 95))}`],
    ['Latency — all stages p50 / p95', `${s1(pctl(allLat, 50))} / ${s1(pctl(allLat, 95))}`],
    ['Evidence-check agreement', 'n/a — no photos in the seed set'],
  ];

  const md =
    `# Nagorik Setu — measured benchmarks\n\n` +
    `Model \`gemma-4-26b-a4b-it\` (AI Studio) · scored against ${GOLD.length} hand-labelled reports ` +
    `([eval/gold.js](../server/eval/gold.js)) · generated by \`npm run eval\` on ${new Date().toISOString().slice(0, 10)}.\n\n` +
    `| Metric | Value |\n|---|---|\n` +
    rows.map(([k, v]) => `| ${k} | ${v} |`).join('\n') +
    `\n\n` +
    `**Notes.** Numbers are on a curated 38-report set with intentionally clear clusters, so dedupe ` +
    `scores are an upper bound, not a field estimate. Category "misses" are mostly defensible ` +
    `disagreements (e.g. a flooded road labelled \`water\` vs \`infrastructure\`). Latency is the ` +
    `known Gemma-4 thinking floor and is why intake is async (202 + SSE). No photos were seeded, ` +
    `so Stage 3 evidence agreement is not measured here.\n`;

  console.log('\n' + md);

  const outPath = new URL('./results.md', import.meta.url);
  fs.writeFileSync(outPath, md);
  console.log(`written: server/eval/results.md`);

  await mongoose.disconnect();
}

main().catch((err) => { console.error('[eval] fatal:', err); process.exit(1); });
